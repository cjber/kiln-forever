#!/usr/bin/env python3
"""Regenerate bridge/src/glyphs.js from the client's FRIZQT__ font.

    FOREVER_CORE=/path/to/forever-core python3 tools/gen_glyphs.py

The game draws every line with FRIZQT__ (the GameFont* objects), so the bridge may
only send characters that font has. The font is read from the pinned client build
through forever-core's wowmock, which caches the files it fetches:

    ui = wowmock.Ui()
    ui.wago.file(ui.wago.fdid("fonts/frizqt__.ttf"))

The output is the sorted list of code points in the font's best cmap. format.js's
fitFont keeps those and rewrites or drops the rest.
"""

import io
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOREVER_CORE = Path(os.environ.get("FOREVER_CORE", ROOT.parent / "forever-core")).expanduser()
WOWMOCK = FOREVER_CORE / "tools" / "wowmock"
if not (WOWMOCK / "wowmock.py").is_file():
    sys.exit(f"wowmock.py not found in {WOWMOCK}; set FOREVER_CORE to the forever-core checkout")
sys.path.insert(0, str(WOWMOCK))

import wowmock  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402

OUT = ROOT / "bridge/src/glyphs.js"
FONT = "fonts/frizqt__.ttf"


def main():
    ui = wowmock.Ui()
    data = ui.wago.file(ui.wago.fdid(FONT))
    points = sorted(TTFont(io.BytesIO(data)).getBestCmap())
    body = ",\n".join("  " + ", ".join(str(p) for p in points[i:i + 16]) for i in range(0, len(points), 16))
    OUT.write_text(
        "// Generated by tools/gen_glyphs.py from the client's FRIZQT__ font.\n"
        f"// Build {wowmock.BUILD}; {len(points)} code points. format.js keeps exactly these.\n"
        "\n"
        "export const GLYPHS = [\n"
        f"{body},\n"
        "];\n",
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: {len(points)} code points from {FONT} (build {wowmock.BUILD})")


if __name__ == "__main__":
    main()
