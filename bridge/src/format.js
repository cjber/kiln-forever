// Markdown -> WoW font-string markup, markdown -> plain text, and fitting text to
// the one font the client can draw.

import { GLYPHS } from './glyphs.js';

const GOLD = 'ffffd100';
const WHITE = 'ffffffff';
const CODE = 'ffa8c7fa';
const DIM = 'ff9d9d9d';
// FRIZQT__ has one face, so emphasis is colour. Bold is the stock white; italic and
// strikethrough, which the font cannot draw, get a colour each.
const BOLD = WHITE;
const ITALIC = 'ffb8c7ff'; // pale blue
const STRIKE = 'ff9d9d9d'; // dim grey

const color = (hex, s) => `|c${hex}${s}|r`;

// WoW treats "|" as an escape character; double it so text can't inject markup.
export function escapeWow(s) {
  return String(s ?? '').replace(/\|/g, '||');
}

// ---------------------------------------------------------------------------
// The game's font

// Every character FRIZQT__ can draw, generated by tools/gen_glyphs.py.
const COVERED = new Set(GLYPHS);

// Common symbols the font lacks, written the plain way people already read them.
const SUBSTITUTIONS = new Map([
  ['\t', '    '], ['\u2190', '<-'], ['\u2192', '->'], ['\u2191', '^'], ['\u2193', 'v'], ['\u2194', '<->'],
  ['\u2713', '+'], ['\u2714', '+'], ['\u2611', '+'],
  ['\u2717', 'x'], ['\u2718', 'x'],
  ['\u2610', '[ ]'], ['\u25a1', '[ ]'],
  ['\u25a0', '[x]'], ['\u2612', '[x]'],
  ['\u25aa', '*'], ['\u25ab', '*'],
  ['\u2605', '*'], ['\u2606', '*'],
  ['\u2665', '<3'], ['\u263a', ':)'],
]);

// Fit text to FRIZQT__. Keep what the font covers (NFC); otherwise use its NFKD
// decomposition when every part is covered; otherwise the substitution above;
// otherwise drop it (emoji and the like). Newlines stay.
export function fitFont(value) {
  const text = String(value ?? '').normalize('NFC');
  let out = '';
  for (const ch of text) {
    if (ch === '\n' || COVERED.has(ch.codePointAt(0))) {
      out += ch;
      continue;
    }
    const decomposed = ch.normalize('NFKD');
    if ([...decomposed].every((part) => COVERED.has(part.codePointAt(0)))) {
      out += decomposed;
      continue;
    }
    const substitute = SUBSTITUTIONS.get(ch);
    if (substitute !== undefined) out += substitute;
  }
  return out;
}

// Every display string in a snapshot goes through fitFont once, where the snapshot
// is built. Identifiers and paths are left alone so commands still address kiln.

// ---------------------------------------------------------------------------
// Inline markup

function inline(line) {
  let s = escapeWow(line);
  // Inline code first so its contents aren't formatted further.
  const codes = [];
  s = s.replace(/`([^`]+)`/g, (_, c) => {
    codes.push(c);
    return `\u0000${codes.length - 1}\u0000`;
  });
  // Backslash escapes are held aside so their characters can't become markup.
  const escapes = [];
  s = s.replace(/\\([\\`*_{}\[\]()#+\-.!~|>])/g, (_, c) => {
    escapes.push(c);
    return `\u0001${escapes.length - 1}\u0001`;
  });
  s = s.replace(/!\[([^\]]*)\]\([^)]+\)/g, '[image: $1]');
  s = s.replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
  s = s.replace(/<((?:https?:\/\/|mailto:)[^>\s]+)>/g, (_, url) => url.replace(/^mailto:/, ''));
  // Bold italic, then bold, then strike, then italic.
  s = s.replace(/\*\*\*([^*\n]+)\*\*\*/g, (_, t) => color(BOLD, t));
  s = s.replace(/___([^_\n]+)___/g, (_, t) => color(BOLD, t));
  s = s.replace(/\*\*([^*\n]+)\*\*/g, (_, t) => color(BOLD, t));
  s = s.replace(/__([^_\n]+)__/g, (_, t) => color(BOLD, t));
  s = s.replace(/~~([^~\n]+)~~/g, (_, t) => color(STRIKE, t));
  s = s.replace(/(^|[^\w*])\*([^*\s](?:[^*\n]*?[^*\s])?)\*(?![\w*])/g, (_, pre, t) => pre + color(ITALIC, t));
  s = s.replace(/(^|[^\w_])_([^_\s](?:[^_\n]*?[^_\s])?)_(?![\w_])/g, (_, pre, t) => pre + color(ITALIC, t));
  s = s.replace(/\u0000(\d+)\u0000/g, (_, i) => color(CODE, codes[Number(i)]));
  s = s.replace(/\u0001(\d+)\u0001/g, (_, i) => escapes[Number(i)]);
  return s;
}

// One source line, with its hard-break marker read: two trailing spaces or a
// trailing backslash. The marker itself is removed.
function linePart(raw) {
  const match = /^(.*?)(\s*)$/.exec(raw);
  const text = match ? match[1] : raw;
  const trailing = match ? match[2] : '';
  if (trailing.length >= 2) return { text, br: true };
  const slash = /\\$/.test(text);
  return { text: slash ? text.slice(0, -1) : text, br: slash };
}

// ---------------------------------------------------------------------------
// Blocks

export function markdownToWow(md, { maxChars = 3500 } = {}) {
  let text = String(md ?? '').replace(/\r\n/g, '\n');
  let truncated = false;
  if (text.length > maxChars) {
    text = text.slice(0, maxChars);
    truncated = true;
  }
  const out = [];
  let pending = null;
  let inFence = false;

  // A paragraph or list item: its lines join with one space unless a line ended in
  // a hard break, and a blank line flushed it already.
  const flush = () => {
    if (!pending) return;
    let body = '';
    for (let i = 0; i < pending.parts.length; i++) {
      const part = pending.parts[i];
      body += inline(part.text);
      if (i < pending.parts.length - 1) body += part.br ? '\n' : ' ';
    }
    out.push(pending.prefix + body);
    pending = null;
  };
  const blank = () => {
    flush();
    if (out.length > 0 && out[out.length - 1] !== '') out.push('');
  };

  for (const raw of text.split('\n')) {
    if (/^\s*```/.test(raw)) {
      flush();
      inFence = !inFence;
      continue;
    }
    if (inFence) {
      out.push(color(CODE, '  ' + escapeWow(raw)));
      continue;
    }
    if (raw.trim() === '') {
      blank();
      continue;
    }
    let match;
    if ((match = /^\s{0,3}(#{1,6})\s+(.*)$/.exec(raw))) {
      flush();
      out.push(color(GOLD, inline(match[2].replace(/\s+#+\s*$/, ''))));
    } else if (/^\s{0,3}((\*\s*){3,}|(-\s*){3,}|(_\s*){3,})$/.test(raw)) {
      flush();
      out.push(color(DIM, '-----'));
    } else if (/^\s*\|.*\|\s*$/.test(raw)) {
      flush();
      if (/^\s*\|[\s:|-]+\|\s*$/.test(raw)) continue; // table separator row
      out.push(inline(raw.trim().replace(/^\||\|$/g, '').split('|').map((cell) => cell.trim()).join('  ·  ')));
    } else if ((match = /^\s*>\s?(.*)$/.exec(raw))) {
      flush();
      out.push(color(DIM, inline(match[1])));
    } else if ((match = /^(\s*)([-*+])\s+(.*)$/.exec(raw))) {
      flush();
      const depth = Math.min(3, Math.floor(match[1].length / 2));
      let body = match[3];
      let prefix = '  '.repeat(depth) + color(GOLD, '•') + ' ';
      const task = /^\[([ xX])\]\s+(.*)$/.exec(body);
      if (task) {
        const done = task[1].toLowerCase() === 'x';
        prefix += color(done ? GOLD : DIM, done ? '[x]' : '[ ]') + ' ';
        body = task[2];
      }
      pending = { prefix, parts: [linePart(body)] };
    } else if ((match = /^(\s*)(\d+)[.)]\s+(.*)$/.exec(raw))) {
      flush();
      const depth = Math.min(3, Math.floor(match[1].length / 2));
      pending = { prefix: '  '.repeat(depth) + color(GOLD, match[2] + '.') + ' ', parts: [linePart(match[3])] };
    } else {
      const part = linePart(raw.replace(/^\s+/, ''));
      if (pending) pending.parts.push(part);
      else pending = { prefix: '', parts: [part] };
    }
  }
  flush();

  let s = out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
  if (truncated) s += '\n' + color(DIM, '… (open the session in kiln for the rest)');
  return s;
}

export function markdownToPlain(md, { maxChars = 1500 } = {}) {
  let s = String(md ?? '')
    .replace(/```[\s\S]*?```/g, ' (code block) ')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/!\[[^\]]*\]\([^)]+\)/g, '')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    .replace(/^\s*[-*+]\s+/gm, '')
    .replace(/[*_~>|]/g, ' ')
    .replace(/https?:\/\/\S+/g, 'a link')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{2,}/g, '\n')
    .trim();
  if (s.length > maxChars) {
    const cut = s.lastIndexOf('. ', maxChars);
    s = s.slice(0, cut > maxChars / 2 ? cut + 1 : maxChars);
  }
  return s;
}

export function firstLine(md, max = 140) {
  const plain = markdownToPlain(md, { maxChars: max * 3 }).split('\n').find((l) => l.trim()) || '';
  return plain.length > max ? plain.slice(0, max - 1) + '…' : plain;
}
